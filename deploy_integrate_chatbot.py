class SelfAttention(nn.Module):
    def __init__(self, hidden_dim):
        super().__init__()
        self.projection = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.Tanh(),
            nn.Linear(hidden_dim, 1, bias=False)
        )

    def forward(self, encoder_outputs, mask=None):
        energy = self.projection(encoder_outputs)
        if mask is not None:
            energy = energy.squeeze(-1).masked_fill(mask == 0, -1e9).unsqueeze(-1)
        attention_weights = F.softmax(energy, dim=1)
        return encoder_outputs * attention_weights


class BERT_BiLSTM_Attention_CRF(nn.Module):
    def __init__(self, bert_model_name, num_labels, dropout_rate=0.1, lstm_hidden_size=256, lstm_num_layers=1):
        super().__init__()
        self.bert = BertModel.from_pretrained(bert_model_name)
        self.dropout = nn.Dropout(dropout_rate)

        self.bilstm = nn.LSTM(
            input_size=self.bert.config.hidden_size,
            hidden_size=lstm_hidden_size,
            num_layers=lstm_num_layers,
            bidirectional=True,
            batch_first=True
        )

        bilstm_output_dim = lstm_hidden_size * 2
        self.attention = SelfAttention(hidden_dim=bilstm_output_dim)

        fused_dim = self.bert.config.hidden_size + bilstm_output_dim
        self.fusion_projection = nn.Linear(fused_dim, bilstm_output_dim)
        self.fusion_activation = nn.ReLU()

        self.fc = nn.Linear(bilstm_output_dim, num_labels)
        self.crf = CRF(num_labels, batch_first=True)

    def forward(self, input_ids, attention_mask, labels=None):
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        sequence_output = outputs.last_hidden_state
        sequence_output_dropout = self.dropout(sequence_output)

        lstm_out, _ = self.bilstm(sequence_output_dropout)
        attended_out = self.attention(lstm_out, mask=attention_mask)

        combined_features = torch.cat([sequence_output, lstm_out + attended_out], dim=-1)

        fused_out = self.fusion_projection(combined_features)
        fused_out = self.fusion_activation(fused_out)
        fused_out = self.dropout(fused_out)

        emissions = self.fc(fused_out)

        if labels is not None:
            return -self.crf(emissions, labels, mask=attention_mask.bool(), reduction='mean')
        else:
            return self.crf.decode(emissions, mask=attention_mask.bool())

