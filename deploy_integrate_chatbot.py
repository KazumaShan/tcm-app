def extract_entities(text, model, tokenizer, id2label, max_len=64):
    model.eval()
    inputs = tokenizer(
        text,
        max_length=max_len,
        padding='max_length',
        truncation=True,
        return_tensors="pt"
    )

    input_ids = inputs['input_ids'].to(device)
    attention_mask = inputs['attention_mask'].to(device)

    with torch.no_grad():
        predicted_tag_ids = model(input_ids, attention_mask=attention_mask)[0]

    tokens = tokenizer.convert_ids_to_tokens(input_ids[0])
    extracted_entities = []
    current_entity = ""
    current_type = None

    for token, tag_id in zip(tokens[1:], predicted_tag_ids[1:]):
        if token in ["[SEP]", "[PAD]"]:
            break
        label = id2label.get(tag_id, "O")
        if label.startswith("B-"):
            if current_entity:
                extracted_entities.append((current_entity, current_type))
            current_entity = token.replace("##", "")
            current_type = label.split("-")[1]
        elif label.startswith("I-") and current_entity:
            current_entity += token.replace("##", "")
        else:
            if current_entity:
                extracted_entities.append((current_entity, current_type))
                current_entity = ""
                current_type = None

    if current_entity:
        extracted_entities.append((current_entity, current_type))
    return extracted_entities


# ==========================================
# 2. Safety Checker Function (Eighteen Antagonists)
# ==========================================
def check_herb_conflicts(top_results, conflicts):
    warnings = []
    combined_text = " ".join([res for res, score in top_results])

    for c in conflicts:
        a, b = c['herb_a'], c['herb_b']
        if a in combined_text and b in combined_text:
            warnings.append(f"🚨 安全警告: 推荐结果中存在十八反禁忌组合 [{a}] 与 [{b}]！")
    return warnings


# ==========================================
# 3. Define Improved Pipeline with Query Expansion
# ==========================================

def predict_tcm_pipeline_improved(input_text, candidate_pool=formatted_candidates, top_k=5):
    print(f"\n📥 Input Patient Text: '{input_text}'")
    print("-" * 50)

    # ============================================================
    # Step 1: Extract Entities using NER
    # ============================================================
    entities = extract_entities(
        input_text,
        loaded_model,
        loaded_tokenizer,
        loaded_id2label_crf,
        max_len=loaded_max_length
    )

    print("🏷️ Extracted Entities (NER):")

    if not entities:
        print("  ⚠️ No entities detected!")
        return

    for entity, entity_type in entities:
        print(f"  • [{entity_type}] : {entity}")


    # ============================================================
    # Step 1.1: Separate SYM and HER entities
    # ============================================================
    symptoms = [
        entity for entity, etype in entities
        if etype in ["SYM", "B-SYM", "I-SYM"]
    ]

    herbs = [
        entity for entity, etype in entities
        if etype in ["HER", "B-HER", "I-HER"]
    ]

    print(f"\n🩺 Symptoms Used for Matching: {symptoms}")
    print(f"🌿 Herbs Mentioned by Patient: {herbs}")


    # ============================================================
    # Step 1.2: Detect context/role of mentioned herbs
    # ============================================================
    def detect_herb_context(text, herb):
        """
        Determine how the patient mentions the herb.
        This is a lightweight rule-based contextual layer.
        """

        idx = text.find(herb)

        if idx == -1:
            return "MENTIONED"

        # Take surrounding context of the herb
        context_start = max(0, idx - 20)
        context_end = min(len(text), idx + len(herb) + 20)
        context = text[context_start:context_end]

        # Patient is asking whether the herb is effective/suitable
        queried_words = [
            "有效吗",
            "有用吗",
            "可以吗",
            "能缓解吗",
            "能治疗吗",
            "适合吗",
            "能不能吃",
            "能不能用",
            "是否可以",
            "有没有用"
        ]

        # Patient has already taken/used the herb
        taken_words = [
            "已经吃",
            "已经服用",
            "已经用了",
            "正在吃",
            "正在服用",
            "正在用",
            "吃了",
            "服用了",
            "用了",
            "喝了"
        ]

        # Patient is requesting/recommending the herb for themselves
        requested_words = [
            "推荐",
            "应该吃",
            "应该用",
            "想吃",
            "想用",
            "可以用",
            "可以吃"
        ]

        if any(word in context for word in queried_words):
            return "QUERIED"

        if any(word in context for word in taken_words):
            return "TAKEN"

        if any(word in context for word in requested_words):
            return "REQUESTED"

        return "MENTIONED"


    herb_roles = {
        herb: detect_herb_context(input_text, herb)
        for herb in herbs
    }

    if herb_roles:
        print("\n🔎 Herb Context Analysis:")
        for herb, role in herb_roles.items():
            print(f"  • {herb} → {role}")


    # ============================================================
    # Step 1.3: Construct SBERT query using SYM ONLY
    # ============================================================
    if symptoms:
        symptom_keywords = "、".join(symptoms)

        expanded_query = (
            f"患者主诉症状表现为：{symptom_keywords}，"
            f"应选用何种中药或经典方剂进行调理治疗？"
        )
    else:
        # Fallback if no symptoms were detected
        expanded_query = input_text

    print(
        f"\n🔍 Expanded Query Sent to SBERT Matcher: "
        f"'{expanded_query}'"
    )


    # ============================================================
    # Step 2: SBERT Similarity Matching
    # ============================================================
    query_embedding = sbert_model.encode(
        expanded_query,
        convert_to_tensor=True
    )

    candidate_embeddings = sbert_model.encode(
        candidate_pool,
        convert_to_tensor=True
    )

    similarity_scores = torch.nn.functional.cosine_similarity(
        query_embedding,
        candidate_embeddings
    )


    # ============================================================
    # Step 2.1: Herb Contextual Weighting
    # ============================================================
    #
    # Important:
    # HER is NOT added into the SBERT query.
    # Instead, it is used as a separate contextual signal.
    #
    # Small bonus values are used so that herb context does not
    # overpower symptom-based semantic matching.
    # ============================================================

    HERB_BONUS = {
        "QUERIED": 0.02,
        "REQUESTED": 0.02,
        "TAKEN": 0.00,
        "MENTIONED": 0.00
    }

    adjusted_results = []

    for item, similarity in zip(
        candidate_pool,
        similarity_scores.tolist()
    ):

        final_score = similarity
        herb_adjustment = 0.0
        matched_herb = None
        matched_role = None

        # Check whether candidate herb was explicitly mentioned
        # by the patient.
        for herb, role in herb_roles.items():

            # Candidate may contain additional information,
            # so use substring matching.
            if herb in item:

                matched_herb = herb
                matched_role = role

                herb_adjustment = HERB_BONUS.get(role, 0.0)
                final_score += herb_adjustment

                break

        adjusted_results.append({
            "item": item,
            "sbert_score": similarity,
            "herb_adjustment": herb_adjustment,
            "final_score": final_score,
            "matched_herb": matched_herb,
            "herb_role": matched_role
        })


    # ============================================================
    # Step 2.2: Sort using FINAL SCORE
    # ============================================================
    adjusted_results = sorted(
        adjusted_results,
        key=lambda x: x["final_score"],
        reverse=True
    )

    top_results = adjusted_results[:top_k]


    # ============================================================
    # Step 3: Display Final Recommendations
    # ============================================================
    print(
        f"\n🌿 Top {top_k} Recommendation Results "
        f"(Herbs & Prescriptions):"
    )

    for rank, result in enumerate(top_results, start=1):

        item = result["item"]
        sbert_score = result["sbert_score"]
        herb_adjustment = result["herb_adjustment"]
        final_score = result["final_score"]

        print(
            f"  {rank}. {item} "
            f"(SBERT: {sbert_score:.4f}, "
            f"Herb Adjustment: {herb_adjustment:+.4f}, "
            f"Final Score: {final_score:.4f})"
        )

        if result["matched_herb"]:
            print(
                f"      ↳ Patient-mentioned herb: "
                f"{result['matched_herb']} "
                f"({result['herb_role']})"
            )


    # ============================================================
    # Step 4: Check Conflict Rules
    # ============================================================

    # Convert results back to the original
    # (item, score) format required by check_herb_conflicts()
    top_results_for_conflict = [
        (result["item"], result["final_score"])
        for result in top_results
    ]

    conflicts_found = check_herb_conflicts(
        top_results_for_conflict,
        conflicts_data
    )

    if conflicts_found:
        print("\n⚠️ 禁忌校验系统检测结果：")

        for warning in conflicts_found:
            print(f"  {warning}")

    else:
        print(
            "\n✅ 十八反禁忌校验通过："
            "推荐结果无配伍冲突。"
        )

